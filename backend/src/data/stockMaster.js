// Dedupe and build uppercase lookup
const _master = [];
const _seen   = new Set();
for (const row of STOCKS) {
  if (!_seen.has(row.s)) { _seen.add(row.s); _master.push({ symbol: row.s, name: row.n }); }
}

/**
 * Search stocks by symbol prefix, symbol contains, or name contains.
 * Priority: 0=exact prefix, 1=symbol contains, 2=name contains
 * Returns max `limit` results.
 */
function search(query, limit = 10) {
  if (!query || query.length < 1) return _master.slice(0, limit);
  const q   = query.toUpperCase().trim();
  const qlo = query.toLowerCase().trim();

  const results = [];
  for (const stock of _master) {
    const sym  = stock.symbol;
    const name = stock.name.toLowerCase();
    let   rank = -1;
    if (sym === q)               rank = 0;   // exact
    else if (sym.startsWith(q)) rank = 1;   // prefix
    else if (sym.includes(q))   rank = 2;   // symbol contains
    else if (name.includes(qlo)) rank = 3;   // name contains
    if (rank >= 0) results.push({ ...stock, _rank: rank });
  }

  results.sort((a, b) => a._rank - b._rank || a.symbol.localeCompare(b.symbol));
  return results.slice(0, limit).map(({ symbol, name }) => ({ symbol, name }));
}

module.exports = { search, count: () => _master.length };
